// System czasem podaje sam region zamiast pisma ('zh-TW' zamiast 'zh-Hant'),
// a 'pt' bez kraju znaczy portugalski europejski. Tu prostujemy takie skroty.
const ALIAS = {
  'zh': 'zh-Hans', 'zh-cn': 'zh-Hans', 'zh-sg': 'zh-Hans',
  'zh-tw': 'zh-Hant', 'zh-hk': 'zh-Hant', 'zh-mo': 'zh-Hant',
  'pt': 'pt-PT', 'no': 'nb', 'nn': 'nb', 'in': 'id', 'iw': 'en',
};

// 'pl-PL' -> 'pl', 'zh-Hans-CN' -> 'zh-Hans'. Nieznany kod = angielski.
function resolve(locale) {
  const tag = String(locale || '').replace('_', '-');
  const parts = tag.split('-');
  while (parts.length) {
    const key = parts.join('-');
    if (STRINGS[key]) return key;
    const alias = ALIAS[key.toLowerCase()];
    if (alias && STRINGS[alias]) return alias;
    const found = Object.keys(STRINGS).find(k => k.toLowerCase() === key.toLowerCase());
    if (found) return found;
    parts.pop();
  }
  return 'en';
}

// Brakujace klucze lataja angielskim - interfejs nigdy nie pokazuje pustki.
const dict = locale => ({ ...STRINGS.en, ...STRINGS[resolve(locale)] });

// Lista do menu wyboru: [kod, nazwa wlasna], angielski pierwszy, reszta alfabetycznie.
const catalogue = () => Object.keys(STRINGS)
  .sort((a, b) => a === 'en' ? -1 : b === 'en' ? 1 : STRINGS[a].name.localeCompare(STRINGS[b].name))
  .map(code => [code, STRINGS[code].name]);

// Podstawienia w stylu "Pobrano {ok} z {total}."
const fill = (text, vars) => String(text).replace(/\{(\w+)\}/g, (m, k) => k in vars ? vars[k] : m);

module.exports = { STRINGS, resolve, dict, catalogue, fill };
